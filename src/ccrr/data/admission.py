"""Read-only verification of the frozen PAD evidence (§4, §32.1/12/13).

The shipped manifest contains digests only, never patient records. It is not
regenerated by preflight: a different dataset requires an explicit new protocol.
"""

from collections import Counter, defaultdict
import csv
import json
from pathlib import Path

from ccrr.codec.metadata import CLASSES, FIELDS, serialize, deserialize
from ccrr.config import sha256
from ccrr.data.pad import preprocess
from ccrr.errors import require

ROLES = ("fit", "calibration", "val_tune", "val_select", "test")
AUDIT = "protocol_audit_20261009"


def read_json(path):
    return json.loads(Path(path).read_text())


def unique_rows(rows, key="img_id"):
    out = {r[key]: r for r in rows}
    require(len(out) == len(rows), "Duplicate evidence member")
    return out


def verify_pairs(rows, protocol, scenario):
    by_id = unique_rows(rows)
    eligible = [r for r in rows if r["reid_observation_eligible"] == "1"]
    groups = defaultdict(lambda: defaultdict(list))
    for r in eligible:
        groups[r["patient_id"]][r["lesion_id"]].append(r["img_id"])
    patients = {
        p
        for p, ls in groups.items()
        if (len(ls) >= 2 if scenario == "p1" else any(len(v) >= 2 for v in ls.values()))
    }
    gallery = {r["img_id"] for r in eligible if r["patient_id"] in patients}
    require(
        len(protocol["gallery"]) == len(gallery)
        and set(protocol["gallery"]) == gallery,
        "Frozen pair gallery membership mismatch",
    )
    queries = unique_rows(protocol["queries"], "query")
    expected = set()
    for name in gallery:
        r = by_id[name]
        pos = {
            n
            for n in gallery
            if n != name
            and by_id[n]["patient_id"] == r["patient_id"]
            and (
                (by_id[n]["lesion_id"] != r["lesion_id"])
                if scenario == "p1"
                else (by_id[n]["lesion_id"] == r["lesion_id"])
            )
        }
        if not pos:
            continue
        expected.add(name)
        require(name in queries, "Missing legal pair query")
        q = queries[name]
        neg = {n for n in gallery if by_id[n]["patient_id"] != r["patient_id"]}
        matched = {
            n
            for n in neg
            if any(
                (by_id[n]["diagnostic"], by_id[n]["region"])
                == (by_id[p]["diagnostic"], by_id[p]["region"])
                for p in pos
            )
        }
        require(q["patient_id"] == r["patient_id"], "Pair patient mismatch")
        for field, target in [
            ("positive_gallery", pos),
            ("negative_gallery", neg),
            ("diagnosis_region_matched_negative_union", matched),
        ]:
            require(
                len(q[field]) == len(target) and set(q[field]) == target,
                "Pair relationship or matched-negative membership mismatch",
            )
    require(set(queries) == expected, "Illegal or missing pair queries")
    return {"gallery": len(gallery), "queries": len(queries), "patients": len(patients)}


def verify_source_row(row, source, cleaned):
    require(all(source[k] == cleaned[k] for k in FIELDS), "26 source fields differ")
    require(all(row[k] == cleaned[k] for k in row), "Role/source metadata mismatch")
    obj = {k: source[k] for k in FIELDS}
    require(deserialize(serialize(obj)) == obj, "PAD-M1 source roundtrip mismatch")


def verify_dataset(root, *, pixels=True):
    root = Path(root).resolve()
    frozen = read_json(Path(__file__).with_name("frozen_evidence.json"))
    for relative, expected in frozen["files"].items():
        p = root / relative
        require(
            p.is_file() and sha256(p) == expected,
            f"Frozen evidence mismatch: {relative}",
        )
    with (root / "raw/metadata.csv").open(newline="") as f:
        source = unique_rows(list(csv.DictReader(f)))
    with (root / "study_v1/manifests/clean_manifest.csv").open(newline="") as f:
        clean = unique_rows(list(csv.DictReader(f)))
    inventories = unique_rows(read_json(root / AUDIT / "preprocessing_inventory.json"))
    originals = unique_rows(read_json(root / AUDIT / "image_inventory.json"))
    seen_images, seen_patients = set(), set()
    result = {}
    role_rows = {}
    for role in ROLES:
        rows = read_json(root / AUDIT / "roles" / (role + ".json"))
        role_rows[role] = rows
        names = set(unique_rows(rows))
        patients = {r["patient_id"] for r in rows}
        require(
            not seen_images & names and not seen_patients & patients, "Role overlap"
        )
        seen_images |= names
        seen_patients |= patients
        for r in rows:
            name = r["img_id"]
            require(name in source and name in clean, "Source association missing")
            verify_source_row(r, source[name], clean[name])
            path = (root / r["source_relpath"]).resolve()
            require(path.is_relative_to(root) and path.is_file(), "Invalid source path")
            require(
                sha256(path) == originals[name]["file_sha256"],
                "Original file digest mismatch",
            )
            if pixels:
                x, v, rect, legal, digest = preprocess(path, 512)
                inv = inventories[name]
                require(
                    digest == inv["rgb512_sha256"]
                    and list(rect) == inv["content_rect_xywh"],
                    "512 preprocessing pixels/geometry mismatch",
                )
                require(
                    legal.flatten().nonzero().flatten().tolist()
                    == inv["legal_regions"],
                    "512 legal region mismatch",
                )
                require(
                    x.shape == (3, 512, 512) and v.shape == (1, 512, 512),
                    "512 tensor shape",
                )
        counts = Counter(r["diagnostic"] for r in rows)
        result[role] = {
            "images": len(rows),
            "patients": len(patients),
            "class_n": [counts[c] for c in CLASSES],
            "pairs": {},
        }
        require(
            result[role]["images"] == frozen["counts"][role]["images"]
            and result[role]["patients"] == frozen["counts"][role]["patients"]
            and result[role]["class_n"] == frozen["counts"][role]["class_n"],
            "Frozen counts mismatch",
        )
        for scenario in ("p1", "p2"):
            result[role]["pairs"][scenario] = verify_pairs(
                rows,
                read_json(root / AUDIT / "pair_protocol" / f"{role}_{scenario}.json"),
                scenario,
            )
    require(seen_images == set(clean), "Five roles do not exhaust frozen cleaned set")
    for split, roles in [
        ("train", ("fit", "calibration")),
        ("val", ("val_tune", "val_select")),
        ("test", ("test",)),
    ]:
        original = unique_rows(read_json(root / "study_v1/manifests" / f"{split}.json"))
        require(
            set(original) == {r["img_id"] for role in roles for r in role_rows[role]},
            "Original split membership changed",
        )
    fit = unique_rows(role_rows["fit"])
    local = read_json(
        root / AUDIT / "pair_protocol/fit_local_identity_negative_pairs.json"
    )
    for p in local:
        a, b = fit[p["rgb_img"]], fit[p["gray_img"]]
        require(
            a["patient_id"] == p["anchor_patient"]
            and b["patient_id"] == p["other_patient"]
            and a["patient_id"] != b["patient_id"],
            "Local identity negative pair mismatch",
        )
    require(
        len(local) == 3452
        and set(Counter(p["anchor_patient"] for p in local).values()) == {4},
        "Local identity negative patient quota mismatch",
    )
    return {
        "verified": True,
        "pixels_verified": pixels,
        "roles": result,
        "frozen_manifest_sha256": sha256(
            Path(__file__).with_name("frozen_evidence.json")
        ),
        "evidence_files": len(frozen["files"]),
        "source_images": len(seen_images),
        "source_fields": len(FIELDS),
        "local_negative_pairs": len(local),
        "test_used_for_performance": False,
    }
